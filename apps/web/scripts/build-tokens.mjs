// Writes src/styles/tokens.css from @et/brand, so the website and the app share one set of
// colours and radii. Runs before dev, build and typecheck; the output is gitignored.
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { altusLight, radius, space, webColors } = require('@et/brand');

const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const lines = [];
for (const [key, value] of Object.entries(altusLight)) {
  if (typeof value === 'string') lines.push(`  --color-${kebab(key)}: ${value};`);
}
altusLight.chart.forEach((value, i) => lines.push(`  --color-chart-${i + 1}: ${value};`));
for (const [key, value] of Object.entries(webColors)) lines.push(`  --color-${kebab(key)}: ${value};`);
for (const [key, value] of Object.entries(radius)) lines.push(`  --radius-${key}: ${value}px;`);
for (const [key, value] of Object.entries(space)) lines.push(`  --space-${key}: ${value}px;`);

const css = `/* Generated by scripts/build-tokens.mjs from @et/brand. Do not edit. */\n:root {\n${lines.join('\n')}\n}\n`;
writeFileSync(fileURLToPath(new URL('../src/styles/tokens.css', import.meta.url)), css);
console.log(`tokens.css: ${lines.length} tokens`);
